export type Translator = (key: MessageKey, values?: Record<string, string | number>) => string;

export function createTranslator(language: InterfaceLanguage): Translator {
  const messages = language === "zh-CN" ? zh : en;
  return (key, values = {}) =>
    Object.entries(values).reduce(
      (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
      messages[key],
    );
}

const I18nContext = createContext({
  language: "en" as InterfaceLanguage,
  t: createTranslator("en"),
});

export function I18nProvider({
  language,
  children,
}: {
  language: InterfaceLanguage;
  children: ReactNode;
}) {
  const value = useMemo(() => ({ language, t: createTranslator(language) }), [language]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
